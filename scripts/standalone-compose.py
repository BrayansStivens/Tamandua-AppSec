#!/usr/bin/env python3
"""Writes deploy/compose.yaml: Tamandua in one file, for a server or a platform that takes a single compose file
(Coolify, Dokploy, Portainer, Hostinger's Docker manager). Published images, no clone, no build, no Docker socket.

The Caddyfile and the backup script are embedded from docker/caddy/Caddyfile and scripts/backup-service.sh, so they
never drift: `make standalone` regenerates the file and tests/test_packaging.py checks it is current.
Usage: python3 scripts/standalone-compose.py [--check]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "deploy" / "compose.yaml"


def pinned(name: str) -> str:
    """The image a compose file of this repository pins for `name` (postgres, caddy)."""
    for path in ("compose.yaml", "compose.prod.yaml"):
        found = re.search(rf"image: ({name}:[^\s]+@sha256:[0-9a-f]{{64}})", (ROOT / path).read_text())
        if found:
            return found.group(1)
    raise SystemExit(f"no pinned {name} image")


def embedded(path: str, indent: int) -> str:
    text = (ROOT / path).read_text().replace("$", "$$")  # Compose would interpolate it; the file reads it at run time
    return "\n".join((" " * indent + line) if line else "" for line in text.rstrip("\n").split("\n"))


def version() -> str:
    return re.search(r'^VERSION = "([^"]+)"', (ROOT / "tamandua" / "version.py").read_text(), re.M).group(1)


def render() -> str:
    caddy = embedded("docker/caddy/Caddyfile", 6).replace("{$$TAMANDUA_DOMAIN}", "{$$TAMANDUA_PUBLIC_URL}")
    caddy = caddy.replace("(compose.prod.yaml)", "(deploy/compose.yaml)").replace("for TAMANDUA_DOMAIN", "for TAMANDUA_PUBLIC_URL")
    return f"""# Tamandua in one file: published images, nothing to clone or build, no Docker socket.
# Generated by scripts/standalone-compose.py from the repository's files: edit those and run `make standalone`.
#
#   1. Put this file on the server, or paste it into Coolify, Dokploy, Portainer or Hostinger's Docker manager.
#   2. Set the variables (a .env next to this file, or the platform's environment screen):
#        TAMANDUA_DB_PASSWORD   openssl rand -hex 24
#        TAMANDUA_MASTER_KEY    openssl rand -base64 32   (keep a copy apart: it decrypts every stored secret)
#        TAMANDUA_PUBLIC_URL    https://tamandua.example.com
#   3. docker compose up -d
#      With your own domain and no proxy in front: docker compose --profile https up -d (Caddy gets the certificate).
#      Scheduled backups into ./backups: add --profile backup.
#   4. The first administrator's code: docker compose exec api python -m tamandua setup-code
#
# The worker runs the analysis engines inside its own image (TAMANDUA_ENGINE_RUNNER=local): nothing in this file
# touches the host's Docker. Guide: docs/deploy.md
name: tamandua

x-app: &app
  user: "10001:10001"
  read_only: true
  tmpfs:
    - /tmp:size=256m
  cap_drop:
    - ALL
  security_opt:
    - no-new-privileges:true
  restart: unless-stopped
  depends_on:
    postgres:
      condition: service_healthy
  logging:
    driver: json-file
    options:
      max-size: "10m"
      max-file: "5"

x-env: &env
  TAMANDUA_DATABASE_URL: "postgresql+psycopg://tamandua:${{TAMANDUA_DB_PASSWORD:?set TAMANDUA_DB_PASSWORD (openssl rand -hex 24)}}@postgres:5432/tamandua"
  TAMANDUA_MASTER_KEY: "${{TAMANDUA_MASTER_KEY:?set TAMANDUA_MASTER_KEY (openssl rand -base64 32)}}"
  TAMANDUA_PUBLIC_URL: "${{TAMANDUA_PUBLIC_URL:?set TAMANDUA_PUBLIC_URL (https://your-domain)}}"
  TAMANDUA_ALLOWED_ORIGINS: "${{TAMANDUA_ALLOWED_ORIGINS:-${{TAMANDUA_PUBLIC_URL}}}}"
  # The API is reached through a proxy (Caddy below, or the platform's): its X-Forwarded-For is believed.
  TAMANDUA_FORWARDED_ALLOW_IPS: "${{TAMANDUA_FORWARDED_ALLOW_IPS:-*}}"
  TAMANDUA_DEFAULT_LOCALE: "${{TAMANDUA_DEFAULT_LOCALE:-en}}"
  TAMANDUA_REQUIRE_TOTP: "${{TAMANDUA_REQUIRE_TOTP:-admins}}"
  TAMANDUA_METRICS_TOKEN: "${{TAMANDUA_METRICS_TOKEN:-}}"
  # CI importing SARIF through POST /api/ci/sarif. Empty = off.
  TAMANDUA_IMPORT_TOKEN: "${{TAMANDUA_IMPORT_TOKEN:-}}"
  TAMANDUA_NVD_API_KEY: "${{TAMANDUA_NVD_API_KEY:-}}"
  TAMANDUA_LOG_FORMAT: "${{TAMANDUA_LOG_FORMAT:-text}}"
  # leader: the leader worker runs the periodic tasks. external: a scheduler calls GET /api/cron with this token.
  TAMANDUA_PERIODIC: "${{TAMANDUA_PERIODIC:-leader}}"
  TAMANDUA_CRON_TOKEN: "${{TAMANDUA_CRON_TOKEN:-}}"
  TAMANDUA_DATA_DIR: /data

services:
  postgres:
    image: {pinned("postgres")}
    environment:
      POSTGRES_USER: tamandua
      POSTGRES_DB: tamandua
      POSTGRES_PASSWORD: "${{TAMANDUA_DB_PASSWORD:?set TAMANDUA_DB_PASSWORD}}"
    volumes:
      - tamandua-pg:/var/lib/postgresql
    security_opt:
      - no-new-privileges:true
    shm_size: 128mb
    restart: unless-stopped
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U tamandua -d tamandua"]
      interval: 5s
      timeout: 5s
      retries: 20

  api:
    <<: *app
    image: "${{TAMANDUA_IMAGE:-ghcr.io/brayansstivens/tamandua}}:${{TAMANDUA_VERSION:-{version()}}}"
    environment:
      <<: *env
      TAMANDUA_EMBEDDED_WORKER: "0"
    volumes:
      - tamandua-data:/data
    # This machine only: a proxy (Caddy below, or the platform's) publishes it with HTTPS.
    ports:
      - "${{TAMANDUA_PORT:-127.0.0.1:8766}}:8766"
    healthcheck:
      test: ["CMD", "python", "-c", "import os,sys,urllib.parse as p,urllib.request as r; h=p.urlsplit(os.environ['TAMANDUA_ALLOWED_ORIGINS'].split(',')[0].strip()).netloc; sys.exit(0 if r.urlopen(r.Request('http://127.0.0.1:8766/api/health', headers={{'Host': h}}), timeout=4).status == 200 else 1)"]
      interval: 30s
      timeout: 5s
      retries: 3

  worker:
    <<: *app
    image: "${{TAMANDUA_IMAGE:-ghcr.io/brayansstivens/tamandua}}-worker:${{TAMANDUA_VERSION:-{version()}}}"
    environment:
      <<: *env
      # Engines write their temporary files (image layers, databases) to disk, not to the small in-memory /tmp.
      TMPDIR: /data/tmp
    volumes:
      - tamandua-data:/data

  caddy:
    image: {pinned("caddy")}
    profiles: [https]
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    environment:
      TAMANDUA_PUBLIC_URL: "${{TAMANDUA_PUBLIC_URL:?set TAMANDUA_PUBLIC_URL}}"
    configs:
      - source: caddyfile
        target: /etc/caddy/Caddyfile
    volumes:
      - caddy-data:/data
      - caddy-config:/config
    depends_on:
      api:
        condition: service_started
    read_only: true
    tmpfs:
      - /tmp:size=16m
    cap_drop:
      - ALL
    cap_add:
      - NET_BIND_SERVICE
    security_opt:
      - no-new-privileges:true
    restart: unless-stopped

  backup:
    image: {pinned("postgres")}
    profiles: [backup]
    init: true
    user: "10001:10001"
    entrypoint: ["/bin/sh", "/opt/tamandua/backup-service.sh"]
    environment:
      PGHOST: postgres
      PGUSER: tamandua
      PGDATABASE: tamandua
      PGPASSWORD: "${{TAMANDUA_DB_PASSWORD:?set TAMANDUA_DB_PASSWORD}}"
      BACKUP_INTERVAL_HOURS: "${{TAMANDUA_BACKUP_INTERVAL_HOURS:-24}}"
      BACKUP_KEEP_DAYS: "${{TAMANDUA_BACKUP_KEEP_DAYS:-14}}"
    configs:
      - source: backup
        target: /opt/tamandua/backup-service.sh
    volumes:
      - tamandua-data:/source/data:ro
      - ${{TAMANDUA_BACKUP_DIR:-./backups}}:/backups
    read_only: true
    tmpfs:
      - /tmp:size=64m
    cap_drop:
      - ALL
    security_opt:
      - no-new-privileges:true
    depends_on:
      api:
        condition: service_healthy
    restart: unless-stopped

configs:
  caddyfile:
    content: |
{caddy}
  backup:
    content: |
{embedded("scripts/backup-service.sh", 6)}

volumes:
  tamandua-pg:
  tamandua-data:
  caddy-data:
  caddy-config:
"""


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != content:
            print("deploy/compose.yaml is out of date: run make standalone", file=sys.stderr)
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
